local T = dofile((arg[0]:match('^(.*)[/\\]') or '.') .. '/testlib.lua')
local R = require('madMerick/route')
local Th = require('madMerick/threat')
local Fu = require('madMerick/fuel')
local F = require('fixtures')

local g = R.toGoal(R.START)
T.near(g.roadKm, 1450, 30, 'Port Wakefield to Pine Gap is about 1,450 km by road')
T.near(g.km * R.ROAD_FACTOR, g.roadKm, 1e-9, 'road estimate is the straight line times the factor')
T.eq(g.letters, 'N', 'Pine Gap is north of the start'); T.eq(g.reached, false, 'not there at the start')
T.eq(R.toGoal(R.GOAL).reached, true, 'reached at Pine Gap')
T.eq(R.toGoal({}), nil, 'invalid position has no goal')
T.near(R.progress(R.START), 0, 1e-9, 'no progress at the start')
T.near(R.progress(R.GOAL), 1, 1e-9, 'all the way at Pine Gap')
T.check(R.progress(F.position(-29.0, 134.75)) > 0.4, 'Coober Pedy is well on the way')
T.eq(R.progress(F.position(-40, 138.1)), 0, 'progress never goes below zero')
T.check(R.atStart(F.position(-34.2, 138.15)), 'near the start counts as at the start')
T.check(not R.atStart(F.position(-33.0, 138.0)), 'far from the start does not')

T.eq(Th.level(nil), 'clear', 'no Hoons is clear'); T.eq(Th.level({}), 'clear', 'empty list is clear')
T.eq(Th.level({ 2000 }), 'clear', 'a far Hoon is clear')
T.eq(Th.level({ 2000, 500 }), 'amber', 'a near Hoon is amber')
T.eq(Th.level({ 80, 500 }), 'red', 'a Hoon on you is red')
T.eq(Th.level({ 0 / 0, -5, 'x' }), 'clear', 'bad distances are ignored')

T.eq(Fu.range(100, 0, 50), nil, 'no range before any fuel is used')
T.eq(Fu.range(100, 1, 1), nil, 'no range before enough km')
T.near(Fu.range(100, 10, 20), 200, 1e-9, '10 L over 20 km leaves 200 km on 100 L')
T.eq(Fu.range(0 / 0, 10, 20), nil, 'invalid litres has no range')
T.done('route, threat and range')
