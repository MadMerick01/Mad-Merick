local T = dofile((arg[0]:match('^(.*)[/\\]') or '.') .. '/testlib.lua')
local P = require('tanker/pistol')
local none = P.new({ pistol = function() return nil end, hands = function() return nil end })
T.eq(none:read().installed, false, 'no pistol'); T.eq(none:leftHand(), nil, 'no hands')
local old = P.new({ pistol = function() return { isEquipped = function() return true end } end, hands = function() end })
local r = old:read()
T.eq(r.installed, true, 'pistol found'); T.eq(r.drawn, true, 'drawn'); T.eq(r.loaded, nil, 'no ammo before the pistol has ammo')
local armed = P.new({ pistol = function() return { getAmmo = function() return { loaded = 3, spare = 18 } end } end })
T.eq(armed:read().loaded, 3, 'loaded rounds'); T.eq(armed:read().spare, 18, 'spare rounds')
local weird = P.new({ pistol = function() return { getAmmo = function() return { loaded = 9, spare = 1 } end, isEquipped = function() error('x') end } end })
T.eq(weird:read().loaded, nil, 'more than six loaded is ignored'); T.eq(weird:read().drawn, false, 'a failing call is not drawn')
local hands = P.new({ hands = function() return { getPose = function(hand, kind)
  T.eq(hand, 'left', 'asks for the left hand'); T.eq(kind, 'grip', 'and its grip')
  return { valid = true, pos = {}, dir = {}, up = {}, right = {} } end } end })
T.check(hands:leftHand() ~= nil, 'left hand pose')
local stale = P.new({ hands = function() return { getPose = function() return { valid = false } end } end })
T.eq(stale:leftHand(), nil, 'no pose when tracking is stale')
T.done('pistol')
